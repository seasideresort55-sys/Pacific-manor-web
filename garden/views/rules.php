<h1>購物說明</h1>

<h2 id="shipping">運費</h2>
<p>運費和免運門檻由各店自己在後台設定，結帳時一家店算一次。太平洋莊園的運費是 NT$200，計入免運的商品滿 NT$2,000 就免運。標成不計入免運的商品不會拿去比門檻，購物車會寫還差多少。店家若還沒填運費，畫面上不會把它當成 0。</p>

<h2 id="preorder">預購</h2>
<p>標成新苗預購的苗，規格都是 3.5 吋扦插苗，不分小盆、中盆、大盆。列表、購物車和結帳都會寫預計出貨月份。月份還沒定的，標待補。</p>

<h2 id="pay">付款</h2>
<p>目前用銀行轉帳或 ATM。送出訂單後會看到該店的銀行、帳號和期限，請填轉帳末五碼。店家在後台確認以後，才算收到款。沒有接到信用卡金流。</p>

<h2 id="returns">退換貨</h2>
<p>到貨 7 天內苗木死亡，可以選擇等值點數，或於下次訂單一起補寄。</p>
